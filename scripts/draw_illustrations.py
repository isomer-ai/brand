def dashed_rect(x, y, w, h, fill="none"):
    return f'<path d="M{x} {y}H{x + w}V{y + h}H{x}Z" fill="{fill}" {S} stroke-dasharray="5 4"/>'


def folder(x, y, w, h, fill="white"):
    return f'<path d="M{x} {y}H{x + 18}L{x + 24} {y + 6}H{x + w}V{y + h}H{x}Z" fill="{fill}" {S}/>'


def drop(cx, cy, fill):
    return (f'<path d="M{cx} {cy - 9}C{cx + 6} {cy - 1} {cx + 6} {cy + 6} {cx} {cy + 6}'
            f'C{cx - 6} {cy + 6} {cx - 6} {cy - 1} {cx} {cy - 9}Z" fill="{fill}" {S}/>')


def briefcase(x, y, w, h, fill):
    hw = w * 0.32
    return "\n".join([line((x + hw, y), (x + hw, y - 6), (x + w - hw, y - 6), (x + w - hw, y)),
                      rect(x, y, w, h, fill), line((x, y + h * 0.4), (x + w, y + h * 0.4))])


def clock(cx, cy, r, fill, hands=((0, -0.7), (0.5, 0.25))):
    out = [circle(cx, cy, r, fill)]
    out += [line((cx + dx * (r - 6), cy + dy * (r - 6)), (cx + dx * (r - 2), cy + dy * (r - 2)))
            for dx, dy in ((0, -1), (1, 0), (0, 1), (-1, 0))]
    out += [line((cx, cy), (cx + hx * r, cy + hy * r)) for hx, hy in hands]
    out.append(f'<circle cx="{cx}" cy="{cy}" r="2.5" fill="{INK}"/>')
    return "\n".join(out)


def text_lines(x, y, lengths, gap=10):
    return "\n".join(line((x, y + i * gap), (x + ln, y + i * gap)) for i, ln in enumerate(lengths))


