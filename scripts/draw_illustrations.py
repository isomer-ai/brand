"""Draw AI-generated illustrations in the isomer.ai style into illustrations/new/.

These were generated by Claude (Anthropic's AI), not drawn by a designer.

    python3 scripts/draw_illustrations.py

The isomer.ai set is drawn in Figma; these follow its vocabulary so they sit beside it:
a 2px Isomer Blue outline with square corners, flat fills from one accent family per
illustration (orange, purple or lime) plus white and cool gray, documents with folded
corners, envelopes, "!" and check badges, the "Ai" tile, offset duplicates for depth,
and thick pale strokes under highlighted lines. No gradients and no live text.
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "illustrations" / "new"

INK = "#000441"
GRAY = "#DADFE8"
ORANGE, PEACH = "#FF9E6E", "#FFE0D4"
PURPLE, LAVENDER, LILAC, MIST = "#9288FF", "#BCB6FF", "#CFCBFF", "#E8ECFF"
LIME, PALE_LIME = "#D5F22A", "#F5F9D6"
S = f'stroke="{INK}" stroke-width="2" stroke-miterlimit="10"'


def svg(body, title, w=160, h=160):
    return (f'<svg width="{w}" height="{h}" viewBox="0 0 {w} {h}" fill="none" '
            f'xmlns="http://www.w3.org/2000/svg">\n'
            f'<!-- Generated by Claude (Anthropic AI) in the isomer.ai illustration style. Not drawn by a designer. -->\n'
            f'<title>{title}</title>\n{body}\n</svg>\n')


def rect(x, y, w, h, fill="white"):
    return f'<path d="M{x} {y}H{x + w}V{y + h}H{x}Z" fill="{fill}" {S}/>'


def line(*pts, width=2, color=INK, dash=None):
    d = "M" + " L".join(f"{x} {y}" for x, y in pts)
    extra = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<path d="{d}" stroke="{color}" stroke-width="{width}" stroke-miterlimit="10"{extra}/>'


def doc(x, y, w, h, fill="white", fold=12, lines=(), hl=None, hl_color=GRAY):
    """A page with a folded corner. lines: (y_offset, length) pairs; hl: index of the highlighted line."""
    out = [f'<path d="M{x} {y}H{x + w - fold}L{x + w} {y + fold}V{y + h}H{x}Z" fill="{fill}" {S}/>',
           f'<path d="M{x + w - fold} {y}V{y + fold}H{x + w}" {S}/>']
    for i, (dy, ln) in enumerate(lines):
        if i == hl:
            out.append(line((x + 9, y + dy), (x + 9 + ln, y + dy), width=8, color=hl_color))
        out.append(line((x + 9, y + dy), (x + 9 + ln, y + dy)))
    return "\n".join(out)


def shadow_doc(x, y, w, h, fill, dx=8, dy=8, fold=12):
    return f'<path d="M{x + dx} {y + dy}H{x + dx + w - fold}L{x + dx + w} {y + dy + fold}V{y + dy + h}H{x + dx}Z" fill="{fill}" {S}/>'


def envelope(x, y, w, h, fill="white", flap=None):
    out = [rect(x, y, w, h, fill)]
    if flap:
        out.append(line((x + 3, y + 5), (x + w / 2, y + h * 0.58), (x + w - 3, y + 5), width=7, color=flap))
    out.append(line((x, y), (x + w / 2, y + h * 0.6), (x + w, y)))
    return "\n".join(out)


def circle(cx, cy, r, fill="white"):
    return f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{fill}" {S}/>'


def alert(cx, cy, r=14, fill=PEACH):
    return "\n".join([circle(cx, cy, r, fill),
                      f'<path d="M{cx - 1.25} {cy - r * 0.55}H{cx + 1.25}V{cy + r * 0.12}H{cx - 1.25}Z" fill="{INK}"/>',
                      f'<circle cx="{cx}" cy="{cy + r * 0.42}" r="1.7" fill="{INK}"/>'])


def check(cx, cy, r=13, fill=PURPLE):
    return "\n".join([circle(cx, cy, r, fill),
                      line((cx - r * 0.5, cy), (cx - r * 0.12, cy + r * 0.42), (cx + r * 0.55, cy - r * 0.42))])


def cross(cx, cy, r=11, fill=PEACH):
    k = r * 0.38
    return "\n".join([circle(cx, cy, r, fill),
                      line((cx - k, cy - k), (cx + k, cy + k)), line((cx + k, cy - k), (cx - k, cy + k))])


def dollar(cx, cy, s=1.0, width=2.5):
    d = (f"M{cx + 6 * s} {cy - 7 * s}C{cx + 4 * s} {cy - 10 * s} {cx - 6 * s} {cy - 10 * s} {cx - 6 * s} {cy - 4 * s}"
         f"C{cx - 6 * s} {cy + 1 * s} {cx + 6 * s} {cy - 1 * s} {cx + 6 * s} {cy + 4 * s}"
         f"C{cx + 6 * s} {cy + 10 * s} {cx - 4 * s} {cy + 10 * s} {cx - 6 * s} {cy + 7 * s}"
         f"M{cx} {cy - 12 * s}V{cy + 12 * s}")
    return f'<path d="{d}" stroke="{INK}" stroke-width="{width}" stroke-miterlimit="10"/>'


def ai_tile(x, y, w, h, fill=LIME):
    """The 'Ai' tile, with the letters drawn as strokes."""
    ax, base, top = x + w * 0.2, y + h * 0.78, y + h * 0.26
    aw = w * 0.36
    return "\n".join([rect(x, y, w, h, fill),
                      f'<path d="M{ax} {base}L{ax + aw / 2} {top}L{ax + aw} {base}M{ax + aw * 0.2} {base - (base - top) * 0.36}H{ax + aw * 0.8}" stroke="{INK}" stroke-width="2.5" stroke-miterlimit="10"/>',
                      line((x + w * 0.74, y + h * 0.44), (x + w * 0.74, base), width=2.5),
                      f'<circle cx="{x + w * 0.74}" cy="{y + h * 0.31}" r="1.9" fill="{INK}"/>'])


def arrow_head(x, y, direction, size=6):
    pts = {"up": [(x - size, y + size), (x, y), (x + size, y + size)],
           "down": [(x - size, y - size), (x, y), (x + size, y - size)],
           "left": [(x + size, y - size), (x, y), (x + size, y + size)],
           "right": [(x - size, y - size), (x, y), (x - size, y + size)]}[direction]
    return line(*pts)


def person(cx, top, head=13, fill=LAVENDER, body_fill=MIST, width=54):
    """Circle head, curved shoulders, flat base, as in the isomer.ai career and specialist art."""
    hy = top + head
    sy = hy + head + 6
    half = width / 2
    return "\n".join([
        f'<path d="M{cx - half} {sy + 30}C{cx - half} {sy + 8} {cx - half * 0.55} {sy} {cx} {sy}C{cx + half * 0.55} {sy} {cx + half} {sy + 8} {cx + half} {sy + 30}Z" fill="{body_fill}" {S}/>',
        circle(cx, hy, head, fill)])


